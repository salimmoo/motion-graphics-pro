#!/usr/bin/env node
/*
 * Build helper for the MGP library (optional; the source files work as they are).
 *   node lib/build.js
 * Writes:
 *   dist/mgp.js        every module in one classic script (one <script> tag, file:// safe)
 *   dist/mgp-packs.js  core + pack-scenes only (old name dist/mgp-paket.js)
 *   index.mjs          ES-module entry: imports the source files in order, re-exports MGP.<name>
 * Also smoke-tests that every file loads without a DOM and lists what it registered on MGP.
 */
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const LIB = __dirname;
const PAKET = ["pack-scenes/engine.js", "pack-scenes/data.js", ...["a1", "a2", "b", "c", "d", "e", "t"].map((k) => `pack-scenes/scenes-${k}.js`)];
// modules that others depend on load first
const FIRST = ["figure3d.js", "vector-kit.js", "spring.js"];
// v2.4 renamed some files (peta.js -> map.js, ...): sort by the old names so the bundle order, and its output, stays the same
const OLD_NAME = { "map.js": "peta.js", "face.js": "wajah.js", "field.js": "medan.js", "fold-pattern.js": "lipat-pola.js" };
const sortKey = (f) => OLD_NAME[f] || f;
const mods = fs.readdirSync(LIB).filter((f) => f.endsWith(".js") && f !== "build.js").sort((a, b) => (sortKey(a) < sortKey(b) ? -1 : sortKey(a) > sortKey(b) ? 1 : 0));
const ORDER = ["core/mgp-core.js", ...FIRST.filter((f) => mods.includes(f)), ...mods.filter((f) => !FIRST.includes(f)), ...PAKET];

const read = (f) => fs.readFileSync(path.join(LIB, f), "utf8");
const banner = (files) => `/* MGP motion library bundle (generated by lib/build.js, do not edit). Files: ${files.join(", ")} */\n`;
fs.mkdirSync(path.join(LIB, "dist"), { recursive: true });
fs.writeFileSync(path.join(LIB, "dist/mgp.js"), banner(ORDER) + ORDER.map((f) => `\n/* ==== ${f} ==== */\n` + read(f)).join("\n"));
const P = ["core/mgp-core.js", ...PAKET];
fs.writeFileSync(path.join(LIB, "dist/mgp-packs.js"), banner(P) + P.map((f) => `\n/* ==== ${f} ==== */\n` + read(f)).join("\n"));

// smoke test without DOM: load every file, see what lands on MGP
const sandbox = { console, Math, JSON, Promise, WeakMap, Map, Set, Object, Array, Number, String, Symbol, Error, setTimeout, clearTimeout };
sandbox.globalThis = sandbox; vm.createContext(sandbox);
const before = {};
ORDER.forEach((f) => {
  try { vm.runInContext(read(f), sandbox, { filename: f }); }
  catch (e) { console.error("LOAD FAIL", f, e.message); process.exitCode = 1; }
  const keys = Object.keys(sandbox.MGP || {}).filter((k) => !before[k]); keys.forEach((k) => (before[k] = f));
});
const names = Object.keys(sandbox.MGP || {}).filter((k) => k !== "paketData" && k !== "packsData");
const ident = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : null);
const idx = `/* MGP ES-module entry (generated by lib/build.js). The source files are classic scripts that register on
   globalThis.MGP; importing them here runs them in order, then each module is re-exported by name.
   import MGP, { figure3d, packs } from "./lib/index.mjs";   (serve over http(s); browsers block ES modules on file://) */
${ORDER.map((f) => `import "./${f}";`).join("\n")}
const MGP = globalThis.MGP;
${names.filter(ident).map((k) => `export const ${k} = MGP.${k};`).join("\n")}
export default MGP;
`;
fs.writeFileSync(path.join(LIB, "index.mjs"), idx);
console.log("modules:", names.map((k) => `${k} <- ${before[k]}`).join("\n         "));
console.log("dist/mgp.js", fs.statSync(path.join(LIB, "dist/mgp.js")).size, "bytes; dist/mgp-packs.js", fs.statSync(path.join(LIB, "dist/mgp-packs.js")).size, "bytes");
