// mgp bundled fonts (render/fonts/): Google Fonts requests from a composition are served from local
// copies, so render, preview and Studio keep working without internet.
//
//  - rewriteFonts(text): https://fonts.googleapis.com/... -> /__fonts/g/...,
//    https://fonts.gstatic.com/... -> /__fonts/gstatic/... (HTML, CSS, JS served by the server).
//  - fontRoute(...): serves /__fonts/fonts.css (all fonts), /__fonts/g/css2?family=... and
//    /__fonts/g/css?family=... (mimics the Google Fonts CSS API), /__fonts/<slug>/<file>.woff2,
//    /__fonts/gstatic/<original path> (mapped through the manifest), and paths .../motion-graphics-pro/render/fonts/...
//    that point outside the server root (lib/fonts.css of the motion-graphics skill).
//  - Families that are not bundled are still fetched from Google (needs internet) and recorded in
//    report.missing; `mgp check` reports them. MGP_FONTS=online turns the redirect off.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { env } from "./names.mjs";
import { L } from "./i18n.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
export const FONT_DIR = path.resolve(here, "..", "fonts");

/** Per-process record: families served locally and the ones that had to go to Google. */
export const report = { local: new Set(), missing: new Set() };
/** Old name (v2.3 / v2.4-dev): the same Sets under the old keys. */
export const laporan = { lokal: report.local, hilang: report.missing };

let MAN = null;
export function manifest() {
  if (MAN) return MAN;
  try { MAN = JSON.parse(fs.readFileSync(path.join(FONT_DIR, "fonts.json"), "utf8")); }
  catch { MAN = { families: [] }; }
  MAN.byName = new Map(MAN.families.map((f) => [f.family.toLowerCase(), f]));
  MAN.byGstatic = new Map(MAN.families.flatMap((f) => f.faces.map((x) => [x.gstatic, x])));
  return MAN;
}
export const isLocal = (fam) => manifest().byName.has(String(fam).replace(/^["']|["']$/g, "").trim().toLowerCase());
export const localFamilies = () => manifest().families.map((f) => f.family);

function faceCss(fam, x, prefix) {
  return `@font-face{font-family:'${fam}';font-style:${x.style};font-weight:${x.weight};${x.stretch ? "font-stretch:" + x.stretch + ";" : ""}` +
    `font-display:block;src:url(${prefix}${x.file}) format('woff2');${x.unicodeRange ? "unicode-range:" + x.unicodeRange + ";" : ""}}`;
}
/**
 * CSS @font-face for one family. want = null: every bundled style/weight; otherwise
 * [{ italic, lo, hi }] from the query (only the requested faces, like Google Fonts: styles that were
 * not requested are not registered, so the browser synthesizes them instead of loading another file later).
 */
export function familyCss(fam, prefix = "/__fonts/", want = null) {
  const f = manifest().byName.get(fam.toLowerCase());
  if (!f) return "";
  // families with an opsz axis have two sets of files: with opsz (the query asks for opsz; also fonts.css) and without
  const opszOk = (x) => x.opsz === undefined || x.opsz === (want ? !!want.opsz : true);
  const faces = f.faces.filter(opszOk).filter((x) => {
    if (!want) return true;
    const [a, b = a] = String(x.weight).split(/\s+/).map(Number);
    return want.some((w) => w.italic === (x.style === "italic") && w.lo <= b && w.hi >= a);
  });
  return `/* ${f.family} (${f.license.id}) */\n` + faces.map((x) => faceCss(f.family, x, prefix)).join("\n") + "\n";
}

/** Parse the axis spec of one family: css2 "ital,wght@0,400;1,300..700" or css v1 "400,700italic". */
export function wantOf(spec, api = "css2") {
  const out = [];
  out.opsz = false;
  if (!spec) return [{ italic: false, lo: 400, hi: 400 }];
  if (api === "css") {
    for (const tok of spec.split(",")) {
      const t = tok.trim().toLowerCase();
      const italic = /i(talic)?$/.test(t) && t !== "bi" ? true : t === "bi";
      const n = /^\d+/.exec(t);
      const w = n ? +n[0] : /^(b|bold|bi|bolditalic)$/.test(t) ? 700 : 400;
      out.push({ italic, lo: w, hi: w });
    }
    return out.length ? out : [{ italic: false, lo: 400, hi: 400 }];
  }
  const [names, vals = ""] = spec.split("@");
  const keys = names.split(",").map((s) => s.trim());
  const iI = keys.indexOf("ital"), iW = keys.indexOf("wght");
  out.opsz = keys.includes("opsz");
  for (const tuple of vals.split(";").filter(Boolean)) {
    const v = tuple.split(",");
    const italic = iI >= 0 ? v[iI] === "1" : false;
    let lo = 400, hi = 400;
    if (iW >= 0 && v[iW]) { const [a, b = a] = v[iW].split("..").map(Number); lo = a; hi = b; }
    out.push({ italic, lo, hi });
  }
  if (!out.length) out.push({ italic: false, lo: 400, hi: 400 });
  return out;
}

/** Write fonts/fonts.css (URLs relative to the fonts/ folder). Called by src/download-font.mjs. */
export function writeCss(dir, man) {
  const head = "/* mgp bundled fonts: generated by src/download-font.mjs, do not edit. Licences: OFL.txt in each folder, summary in ../NOTICE. */\n";
  const css = man.families.map((f) => `/* ${f.family} (${f.license.id}) */\n` + f.faces.filter((x) => x.opsz !== false).map((x) => faceCss(f.family, x, "")).join("\n")).join("\n\n");
  fs.writeFileSync(path.join(dir, "fonts.css"), head + css + "\n");
}

/** Family names from a Google Fonts query (css2: family=A:wght@..&family=B, css v1: family=A:400,700|B). */
export function familiesOf(search) {
  const sp = new URLSearchParams(search);
  return sp.getAll("family").flatMap((v) => v.split("|")).map((v) => v.split(":")[0].replace(/\+/g, " ").trim()).filter(Boolean);
}

/** CSS for a Google Fonts query: local faces + a Google @import for the families that are not bundled. */
export function cssFor(apiPath, search, prefix = "/__fonts/") {
  const specs = new URLSearchParams(search).getAll("family").flatMap((v) => v.split(apiPath === "css" ? "|" : "\u0000"))
    .map((v) => { const i = v.indexOf(":"); return { fam: (i < 0 ? v : v.slice(0, i)).replace(/\+/g, " ").trim(), spec: i < 0 ? "" : v.slice(i + 1) }; })
    .filter((x) => x.fam);
  const fams = specs.map((x) => x.fam);
  const have = [], lack = [];
  for (const f of fams) (isLocal(f) ? have : lack).push(f);
  for (const f of have) report.local.add(manifest().byName.get(f.toLowerCase()).family);
  for (const f of lack) report.missing.add(f);
  let css = "";
  if (lack.length) {
    // @import must come first in a stylesheet; only the families that are not bundled go to Google
    const sp = new URLSearchParams(search);
    sp.delete("family");
    const enc = (x) => encodeURIComponent(x.fam + (x.spec ? ":" + x.spec : "")).replace(/%20/g, "+").replace(/%3A/gi, ":").replace(/%40/g, "@").replace(/%2C/gi, ",").replace(/%3B/gi, ";");
    const keep = specs.filter((x) => !isLocal(x.fam));
    const q = apiPath === "css" ? "family=" + keep.map(enc).join("|") : keep.map((x) => "family=" + enc(x)).join("&");
    css += `@import url("https://fonts.googleapis.com/${apiPath}?${q}${sp.toString() ? "&" + sp : ""}");\n`;
    css += `/* mgp: not in the local fonts (needs internet): ${lack.join(", ")} */\n`;
  }
  for (const x of specs) if (isLocal(x.fam)) css += familyCss(x.fam, prefix, wantOf(x.spec, apiPath));
  return css;
}

const GOOGLE = /(?:https?:)?\/\/fonts\.(googleapis|gstatic)\.com(?=[/"'`\s)>?]|$)/g;
/** Redirect Google Fonts URLs in HTML/CSS/JS text to the local server paths. */
export function rewriteFonts(text) {
  if (env("MGP_FONTS") === "online" || typeof text !== "string" || !text.includes("fonts.g")) return text;
  return text.replace(GOOGLE, (m, k) => (k === "googleapis" ? "/__fonts/g" : "/__fonts/gstatic"));
}

const send = (res, code, body, type) => {
  res.writeHead(code, { "content-type": type, "cache-control": "no-store", "access-control-allow-origin": "*" });
  res.end(body);
};
function sendFont(res, abs) {
  fs.readFile(abs, (err, buf) => {
    if (err) return send(res, 404, L`font not found`, "text/plain");
    res.writeHead(200, { "content-type": abs.endsWith(".css") ? "text/css; charset=utf-8" : abs.endsWith(".txt") ? "text/plain; charset=utf-8" : "font/woff2",
      "content-length": buf.length, "access-control-allow-origin": "*", "cache-control": "max-age=3600" });
    res.end(buf);
  });
}

/**
 * Serve the font paths. Returns true when the request was handled.
 * root is used to check whether .../render/fonts/... really exists in the project.
 */
export function fontRoute(p, req, res, url, root) {
  const inFonts = (rel) => {
    const abs = path.resolve(FONT_DIR, rel);
    return abs.startsWith(FONT_DIR + path.sep) ? abs : null;
  };
  if (p.startsWith("/__fonts/")) {
    const rest = p.slice("/__fonts/".length);
    if (rest === "fonts.css") { send(res, 200, manifest().families.map((f) => familyCss(f.family)).join("\n"), "text/css; charset=utf-8"); return true; }
    if (rest === "fonts.json") { send(res, 200, JSON.stringify({ families: localFamilies() }), "application/json"); return true; }
    const api = /^g\/(css2?)$/.exec(rest) || /^(css2?)$/.exec(rest);
    if (api) { send(res, 200, cssFor(api[1], url.search), "text/css; charset=utf-8"); return true; }
    if (rest === "g" || rest === "gstatic") { send(res, 204, "", "text/plain"); return true; } // preconnect
    if (rest.startsWith("gstatic/")) {
      const g = "/" + rest.slice("gstatic/".length);
      const x = manifest().byGstatic.get(g);
      if (x) { sendFont(res, path.join(FONT_DIR, x.file)); return true; }
      report.missing.add("gstatic:" + g);
      res.writeHead(302, { location: "https://fonts.gstatic.com" + g + url.search }); res.end();
      return true;
    }
    if (rest.startsWith("g/")) { res.writeHead(302, { location: "https://fonts.googleapis.com/" + rest.slice(2) + url.search }); res.end(); return true; }
    const abs = inFonts(rest);
    if (!abs) { send(res, 403, "", "text/plain"); return true; }
    sendFont(res, abs);
    return true;
  }
  // lib/fonts.css (motion-graphics skill) refers to ../../motion-graphics-pro/render/fonts/fonts.css;
  // under the mgp server that path can fall outside the root, so it is mapped to this bundle.
  const m = /\/render\/fonts\/(.+)$/.exec(p);
  if (m && !(root && fs.existsSync(path.join(root, p)))) {
    const abs = inFonts(m[1]);
    if (abs && fs.existsSync(abs)) { sendFont(res, abs); return true; }
  }
  return false;
}

